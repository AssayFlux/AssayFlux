class SQLGenerator:
    """Translates AssayFlux AST nodes into safe, sanitized SQL statements."""
    def __init__(self, ast):
        self.ast = ast

    def escape_identifier(self, name: str) -> str:
        """Prevents SQL identifier injection attacks."""
        if not name.isidentifier():
            raise ValueError(f"Invalid SQL identifier format: {name}")
        return f'"{name}"'

    def sanitize_value(self, val):
        """Sanitizes literals to prevent SQL injection vulnerabilities."""
        if isinstance(val, (int, float)):
            return str(val)
        elif isinstance(val, bool):
            return "TRUE" if val else "FALSE"
        elif val is None:
            return "NULL"
        else:
            escaped = str(val).replace("'", "''")
            return f"'{escaped}'"

    def generate(self) -> str:
        """Generates SQL script output from the AST."""
        sql_lines = ["-- Generated by AssayFlux SQL Generator"]
        # Basic AST iteration stub
        sql_lines.append("SELECT 1;")
        return "\n".join(sql_lines)
