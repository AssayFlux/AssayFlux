"""
SQL generator for AssayFlux Scientific Systems.

Generates a database schema from a project specification.
"""

from __future__ import annotations

import math
from typing import Any

from .base import BaseGenerator, GeneratedFile, GenerationResult


class SqlGenerator(BaseGenerator):
    """Generate SQL schema files from project specifications."""

    ALLOWED_TYPES = {
        "INTEGER",
        "INT",
        "BIGINT",
        "SMALLINT",
        "REAL",
        "FLOAT",
        "DOUBLE",
        "NUMERIC",
        "DECIMAL",
        "TEXT",
        "VARCHAR",
        "CHAR",
        "BOOLEAN",
        "DATE",
        "TIME",
        "TIMESTAMP",
        "BLOB",
    }

    @property
    def name(self) -> str:
        return "sql"

    def generate(
        self,
        spec: dict[str, Any],
    ) -> GenerationResult:
        """Generate a database/schema.sql file."""

        try:
            if not isinstance(spec, dict):
                raise TypeError(
                    "The SQL specification must be a dictionary."
                )

            statements = [
                "-- Generated by AssayFlux Scientific Systems.",
                "-- Review the schema before applying it to a database.",
                "",
            ]

            tables = spec.get("tables", [])

            if not isinstance(tables, list):
                raise ValueError(
                    "The 'tables' field must be a list."
                )

            for table in tables:
                statements.append(self._render_table(table))
                statements.append("")

            content = "\n".join(statements).rstrip() + "\n"

            generated_file = GeneratedFile(
                path="database/schema.sql",
                content=content,
                language="sql",
            )

            return GenerationResult(
                success=True,
                files=[generated_file],
                message="SQL schema generated successfully.",
            )

        except (TypeError, ValueError, KeyError) as exc:
            return GenerationResult(
                success=False,
                errors=[str(exc)],
                message="SQL schema generation failed.",
            )

    @classmethod
    def _render_table(cls, table: Any) -> str:
        """Render one CREATE TABLE statement."""

        if not isinstance(table, dict):
            raise TypeError(
                "Each table specification must be a dictionary."
            )

        table_name = table.get("name")

        if not isinstance(table_name, str):
            raise ValueError(
                "Every table must have a string 'name'."
            )

        quoted_table = cls.escape_identifier(table_name)
        columns = table.get("columns", [])

        if not isinstance(columns, list) or not columns:
            raise ValueError(
                f"Table '{table_name}' must contain a non-empty "
                "'columns' list."
            )

        definitions: list[str] = []
        seen_columns: set[str] = set()

        for column in columns:
            if not isinstance(column, dict):
                raise TypeError(
                    f"Every column in table '{table_name}' "
                    "must be a dictionary."
                )

            column_name = column.get("name")

            if not isinstance(column_name, str):
                raise ValueError(
                    f"Every column in table '{table_name}' "
                    "must have a string 'name'."
                )

            if column_name in seen_columns:
                raise ValueError(
                    f"Duplicate column '{column_name}' "
                    f"in table '{table_name}'."
                )

            seen_columns.add(column_name)

            quoted_column = cls.escape_identifier(column_name)
            sql_type = cls._validate_type(
                column.get("type", "TEXT")
            )

            definition = f"{quoted_column} {sql_type}"

            if column.get("primary_key", False):
                definition += " PRIMARY KEY"

            if column.get("not_null", False):
                definition += " NOT NULL"

            if column.get("unique", False):
                definition += " UNIQUE"

            if "default" in column:
                definition += (
                    " DEFAULT "
                    + cls.sanitize_value(column["default"])
                )

            definitions.append(definition)

        body = ",\n    ".join(definitions)

        return (
            f"CREATE TABLE IF NOT EXISTS {quoted_table} (\n"
            f"    {body}\n"
            ");"
        )

    @staticmethod
    def escape_identifier(name: str) -> str:
        """Validate and quote a SQL identifier."""

        if not isinstance(name, str):
            raise TypeError("SQL identifiers must be strings.")

        if not name or not name.isidentifier():
            raise ValueError(
                f"Invalid SQL identifier: {name!r}"
            )

        return '"' + name.replace('"', '""') + '"'

    @classmethod
    def _validate_type(cls, value: Any) -> str:
        """Validate a SQL type against the supported type list."""

        if not isinstance(value, str):
            raise TypeError("SQL column types must be strings.")

        normalized = value.strip().upper()

        if normalized in cls.ALLOWED_TYPES:
            return normalized

        # Allow bounded character and numeric types.
        import re

        match = re.fullmatch(
            r"(VARCHAR|CHAR|DECIMAL|NUMERIC)\s*"
            r"\(\s*(\d+)"
            r"(?:\s*,\s*(\d+))?\s*\)",
            normalized,
        )

        if match:
            type_name, first, second = match.groups()
            first_number = int(first)
            second_number = int(second) if second else None

            if first_number < 1:
                raise ValueError(
                    f"Invalid SQL type length: {value!r}"
                )

            if second_number is not None:
                if type_name not in {"DECIMAL", "NUMERIC"}:
                    raise ValueError(
                        f"Scale is not supported for {type_name}."
                    )

                if second_number > first_number:
                    raise ValueError(
                        "Numeric scale cannot exceed precision."
                    )

            suffix = (
                f",{second_number}"
                if second_number is not None
                else ""
            )

            return f"{type_name}({first_number}{suffix})"

        raise ValueError(
            f"Unsupported SQL column type: {value!r}"
        )

    @staticmethod
    def sanitize_value(value: Any) -> str:
        """Render a supported Python value as a SQL literal."""

        if value is None:
            return "NULL"

        if isinstance(value, bool):
            return "TRUE" if value else "FALSE"

        if isinstance(value, int):
            return str(value)

        if isinstance(value, float):
            if not math.isfinite(value):
                raise ValueError(
                    "SQL numeric defaults must be finite."
                )

            return repr(value)

        if isinstance(value, str):
            escaped = value.replace("'", "''")
            return f"'{escaped}'"

        raise TypeError(
            f"Unsupported SQL default value: {type(value).__name__}"
        )


# Backward-compatible class name.
SQLGenerator = SqlGenerator