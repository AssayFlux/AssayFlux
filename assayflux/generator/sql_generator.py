"""
SQL Generator for AssayFlux.
"""

from __future__ import annotations

from typing import Any, Dict, List

from .base import BaseGenerator, GeneratedFile, GenerationResult


class SqlGenerator(BaseGenerator):

    @property
    def name(self) -> str:
        return "sql"

    def generate(self, spec: Dict[str, Any]) -> GenerationResult:
        try:
            tables = spec.get("tables", [])
            content = self._render_sql(tables)

            files = [
                GeneratedFile(
                    path="database/schema.sql",
                    content=content,
                    language="sql"
                )
            ]
            return GenerationResult(success=True, files=files, message="SQL schema generated successfully")
        except Exception as e:
            return GenerationResult(success=False, errors=[str(e)])

    def _render_sql(self, tables: List[Dict[str, Any]]) -> str:
        if not tables:
            return """-- Generated by AssayFlux
-- Default schema

CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    email TEXT UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
"""

        lines = ["-- Generated by AssayFlux", ""]
        for table in tables:
            name = table.get("name", "table")
            columns = table.get("columns", [])
            lines.append(f"CREATE TABLE IF NOT EXISTS {name} (")
            col_defs = []
            for col in columns:
                col_name = col.get("name", "col")
                col_type = col.get("type", "TEXT")
                extra = col.get("extra", "")
                col_defs.append(f"    {col_name} {col_type} {extra}".rstrip())
            lines.append(",\n".join(col_defs))
            lines.append(");\n")

        return "\n".join(lines)