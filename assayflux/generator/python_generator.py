"""
Python (Backend / AI) Generator for AssayFlux.
"""

from __future__ import annotations

from typing import Any, Dict

from .base import BaseGenerator, GeneratedFile, GenerationResult


class PythonGenerator(BaseGenerator):

    @property
    def name(self) -> str:
        return "python"

    def generate(self, spec: Dict[str, Any]) -> GenerationResult:
        try:
            backend_type = spec.get("backend", "simple")
            content = self._render_python(spec, backend_type)

            files = [
                GeneratedFile(
                    path="backend/app.py",
                    content=content,
                    language="python"
                )
            ]
            return GenerationResult(success=True, files=files, message="Python backend generated successfully")
        except Exception as e:
            return GenerationResult(success=False, errors=[str(e)])

    def _render_python(self, spec: Dict[str, Any], backend_type: str) -> str:
        title = spec.get("title", "AssayFlux App")

        if backend_type == "flask":
            return f'''"""
{title} - Backend
Generated by AssayFlux
"""

from flask import Flask, jsonify

app = Flask(__name__)

@app.route("/")
def home():
    return jsonify({{"message": "Welcome to {title}", "status": "ok"}})

@app.route("/api/health")
def health():
    return jsonify({{"status": "healthy"}})

if __name__ == "__main__":
    app.run(debug=True, port=5000)
'''
        else:
            return f'''"""
{title} - Simple Python Backend
Generated by AssayFlux
"""

def main():
    print("Welcome to {title}")
    print("Backend is running")

if __name__ == "__main__":
    main()
'''