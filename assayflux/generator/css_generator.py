"""
CSS Generator for AssayFlux.
"""

from __future__ import annotations

from typing import Any, Dict

from .base import BaseGenerator, GeneratedFile, GenerationResult


class CssGenerator(BaseGenerator):

    @property
    def name(self) -> str:
        return "css"

    def generate(self, spec: Dict[str, Any]) -> GenerationResult:
        try:
            theme = spec.get("theme", "light")
            primary = spec.get("primary_color", "#2563eb")
            content = self._render_css(theme, primary)

            files = [
                GeneratedFile(
                    path="css/style.css",
                    content=content,
                    language="css"
                )
            ]
            return GenerationResult(success=True, files=files, message="CSS generated successfully")
        except Exception as e:
            return GenerationResult(success=False, errors=[str(e)])

    def _render_css(self, theme: str, primary: str) -> str:
        bg = "#ffffff" if theme == "light" else "#0f172a"
        text = "#1e293b" if theme == "light" else "#e2e8f0"

        return f"""/* Generated by AssayFlux */
:root {{
    --primary: {primary};
    --bg: {bg};
    --text: {text};
}}

* {{
    margin: 0;
    padding: 0;
    box-sizing: border-box;
}}

body {{
    font-family: system-ui, -apple-system, sans-serif;
    background: var(--bg);
    color: var(--text);
    line-height: 1.6;
    min-height: 100vh;
    display: flex;
    flex-direction: column;
}}

header {{
    background: var(--primary);
    color: white;
    padding: 1rem 2rem;
    display: flex;
    justify-content: space-between;
    align-items: center;
}}

header h1 {{
    font-size: 1.5rem;
}}

nav a {{
    color: white;
    margin-left: 1.5rem;
    text-decoration: none;
    font-weight: 500;
}}

nav a:hover {{
    text-decoration: underline;
}}

main {{
    flex: 1;
    padding: 2rem;
    max-width: 900px;
    margin: 0 auto;
    width: 100%;
}}

.content {{
    margin-top: 1.5rem;
}}

footer {{
    text-align: center;
    padding: 1.5rem;
    font-size: 0.9rem;
    opacity: 0.7;
}}
"""