"""
CSS generator for AssayFlux Scientific Systems.
"""

from __future__ import annotations

import re
from typing import Any

from .base import BaseGenerator, GeneratedFile, GenerationResult


class CssGenerator(BaseGenerator):
    """Generate validated, responsive CSS for an AssayFlux project."""

    DEFAULT_PRIMARY = "#24434A"

    THEMES = {
        "light": {
            "background": "#F6F4EF",
            "surface": "#FFFFFF",
            "text": "#1D292B",
            "muted": "#657174",
            "border": "#DDE3E1",
        },
        "dark": {
            "background": "#0f172a",
            "surface": "#1e293b",
            "text": "#e2e8f0",
            "muted": "#94a3b8",
            "border": "#334155",
        },
    }

    @property
    def name(self) -> str:
        return "css"

    def generate(
        self,
        spec: dict[str, Any],
    ) -> GenerationResult:
        """Generate the CSS stylesheet from a project specification."""

        try:
            if not isinstance(spec, dict):
                raise TypeError(
                    "The CSS generator specification "
                    "must be a dictionary."
                )

            theme = spec.get("theme", "light")
            primary = spec.get(
                "primary_color",
                self.DEFAULT_PRIMARY,
            )

            content = self._render_css(theme, primary)

            generated_file = GeneratedFile(
                path="css/style.css",
                content=content,
                language="css",
            )

            return GenerationResult(
                success=True,
                files=[generated_file],
                message="CSS generated successfully.",
            )

        except (TypeError, ValueError) as exc:
            return GenerationResult(
                success=False,
                errors=[str(exc)],
                message="CSS generation failed.",
            )

    def _render_css(
        self,
        theme: str,
        primary: str,
    ) -> str:
        """Render CSS using a supported theme and validated hex color."""

        if not isinstance(theme, str):
            raise TypeError("The theme must be a string.")

        theme = theme.strip().lower()

        if theme not in self.THEMES:
            raise ValueError(
                f"Unsupported theme: {theme!r}. "
                "Supported themes are 'light' and 'dark'."
            )

        if not isinstance(primary, str):
            raise TypeError(
                "The primary color must be a hexadecimal color string."
            )

        primary = primary.strip()

        if not re.fullmatch(
            r"#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{4}|"
            r"[0-9a-fA-F]{6}|[0-9a-fA-F]{8})",
            primary,
        ):
            raise ValueError(
                "Invalid primary color. Use a hexadecimal color "
                "such as '#24434A' or '#2563eb'."
            )

        palette = self.THEMES[theme]

        return f"""/* Generated by AssayFlux Scientific Systems. */

:root {{
    color-scheme: {theme};

    --primary: {primary};
    --bg: {palette["background"]};
    --surface: {palette["surface"]};
    --text: {palette["text"]};
    --muted: {palette["muted"]};
    --border: {palette["border"]};

    --radius-small: 0.5rem;
    --radius-medium: 0.875rem;
    --radius-large: 1.25rem;

    --shadow-card: 0 8px 24px rgba(0, 0, 0, 0.08);
    --content-width: 1100px;
}}

* {{
    margin: 0;
    padding: 0;
    box-sizing: border-box;
}}

html {{
    scroll-behavior: smooth;
}}

body {{
    min-height: 100vh;
    display: flex;
    flex-direction: column;

    font-family:
        Inter,
        ui-sans-serif,
        system-ui,
        -apple-system,
        BlinkMacSystemFont,
        "Segoe UI",
        sans-serif;

    background: var(--bg);
    color: var(--text);
    line-height: 1.7;
    -webkit-font-smoothing: antialiased;
}}

a {{
    color: var(--primary);
    text-underline-offset: 0.2em;
}}

a:focus-visible,
button:focus-visible,
input:focus-visible,
textarea:focus-visible,
select:focus-visible {{
    outline: 3px solid var(--primary);
    outline-offset: 3px;
}}

header {{
    display: flex;
    align-items: center;
    justify-content: space-between;
    gap: 1.5rem;
    flex-wrap: wrap;

    padding: 1.25rem clamp(1rem, 4vw, 3rem);

    background: var(--primary);
    color: #ffffff;
}}

header h1 {{
    font-size: clamp(1.25rem, 3vw, 1.75rem);
    font-weight: 700;
    line-height: 1.3;
    overflow-wrap: anywhere;
}}

nav {{
    display: flex;
    align-items: center;
    gap: 1.25rem;
    flex-wrap: wrap;
}}

nav a {{
    color: #ffffff;
    text-decoration: none;
    font-weight: 500;
}}

nav a:hover {{
    text-decoration: underline;
}}

main {{
    width: min(100% - 2rem, var(--content-width));
    margin: 0 auto;
    padding: clamp(2rem, 5vw, 4rem) 0;
    flex: 1;
}}

main h2 {{
    margin-bottom: 1rem;
    font-size: clamp(1.75rem, 4vw, 2.5rem);
    line-height: 1.2;
    letter-spacing: -0.025em;
    overflow-wrap: anywhere;
}}

.content {{
    color: var(--text);
    overflow-wrap: anywhere;
}}

.content > * + * {{
    margin-top: 1rem;
}}

.content img,
.content video {{
    display: block;
    max-width: 100%;
    height: auto;
    border-radius: var(--radius-medium);
}}

.content pre {{
    max-width: 100%;
    overflow-x: auto;
    padding: 1rem;
    border: 1px solid var(--border);
    border-radius: var(--radius-small);
    background: var(--surface);
}}

.content code {{
    overflow-wrap: anywhere;
}}

footer {{
    padding: 1.5rem 1rem;
    border-top: 1px solid var(--border);
    color: var(--muted);
    text-align: center;
    font-size: 0.9rem;
}}

@media (max-width: 600px) {{
    header {{
        align-items: flex-start;
        flex-direction: column;
        padding: 1rem;
    }}

    nav {{
        gap: 1rem;
    }}

    main {{
        width: min(100% - 1.5rem, var(--content-width));
    }}
}}

@media (prefers-reduced-motion: reduce) {{
    html {{
        scroll-behavior: auto;
    }}
}}
"""