"""
JavaScript Generator for AssayFlux.
"""

from __future__ import annotations

from typing import Any, Dict

from .base import BaseGenerator, GeneratedFile, GenerationResult


class JsGenerator(BaseGenerator):

    @property
    def name(self) -> str:
        return "javascript"

    def generate(self, spec: Dict[str, Any]) -> GenerationResult:
        try:
            content = self._render_js(spec)
            files = [
                GeneratedFile(
                    path="js/main.js",
                    content=content,
                    language="javascript"
                )
            ]
            return GenerationResult(success=True, files=files, message="JavaScript generated successfully")
        except Exception as e:
            return GenerationResult(success=False, errors=[str(e)])

    def _render_js(self, spec: Dict[str, Any]) -> str:
        app_name = spec.get("title", "AssayFlux App")
        return f"""// Generated by AssayFlux
console.log("{app_name} loaded");

document.addEventListener("DOMContentLoaded", () => {{
    console.log("DOM ready");
}});
"""