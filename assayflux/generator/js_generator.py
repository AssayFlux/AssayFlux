"""
JavaScript generator for AssayFlux Scientific Systems.
"""

from __future__ import annotations

import json
from typing import Any

from .base import BaseGenerator, GeneratedFile, GenerationResult


class JsGenerator(BaseGenerator):
    """Generate JavaScript source code for an AssayFlux project."""

    @property
    def name(self) -> str:
        return "javascript"

    def generate(
        self,
        spec: dict[str, Any],
    ) -> GenerationResult:
        """Generate the main JavaScript file."""

        try:
            if not isinstance(spec, dict):
                raise TypeError(
                    "The JavaScript generator specification "
                    "must be a dictionary."
                )

            content = self._render_js(spec)

            generated_file = GeneratedFile(
                path="js/main.js",
                content=content,
                language="javascript",
            )

            return GenerationResult(
                success=True,
                files=[generated_file],
                message="JavaScript generated successfully.",
            )

        except (TypeError, ValueError) as exc:
            return GenerationResult(
                success=False,
                errors=[str(exc)],
                message="JavaScript generation failed.",
            )

    @staticmethod
    def _render_js(spec: dict[str, Any]) -> str:
        """Render JavaScript with safely encoded application text."""

        app_name = spec.get("title", "AssayFlux App")

        if not isinstance(app_name, str) or not app_name.strip():
            raise ValueError(
                "The application title must be a non-empty string."
            )

        app_name_literal = json.dumps(
            app_name,
            ensure_ascii=True,
        )

        return f'''// Generated by AssayFlux Scientific Systems.

"use strict";

const APP_NAME = {app_name_literal};

console.log(`${{APP_NAME}} loaded`);

document.addEventListener("DOMContentLoaded", () => {{
    console.log("DOM ready");

    const appElement = document.querySelector("[data-assayflux-app]");

    if (appElement) {{
        appElement.setAttribute("data-app-name", APP_NAME);
    }}
}});
'''